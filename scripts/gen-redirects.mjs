// Generates public/_redirects from the shared page table.
//
// Every page that moved needs a 301 from its old path, in every locale, or the
// links already in the wild break. Hand-writing 24+ rules is how the casing
// mistake happened; generating them from the same table the router uses means
// a slug change updates the route, the sitemap, the canonical tag and the
// redirect together or not at all.
//
// Netlify note, learned by taking the site down with it: the CDN lowercases
// deployed paths and serves directories with a trailing slash, and it applies
// its own normalization BEFORE these rules. Never write a rule whose target
// Netlify would itself rewrite back to the source — that is an infinite loop.
// Here old and new paths are genuinely different strings, so there is no cycle.

import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { PAGES, MOVED } from '../src/lib/pages.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_LANGUAGE = 'en';
const LANGUAGES = ['en', 'fr', 'es', 'pt'];
const prefixFor = (lang) => (lang === DEFAULT_LANGUAGE ? '' : `/${lang}`);

const lines = [
  '# GENERATED by scripts/gen-redirects.mjs — do not edit by hand.',
  '# Source of truth: src/lib/pages.js',
  '#',
  '# No SPA catch-all here on purpose. Every route is prerendered to its own',
  '# static index.html, so unmatched URLs fall through to dist/404.html and get a',
  '# real HTTP 404 rather than the home page at 200.',
  '',
  '# --- Legacy paths, 2 Sep 2026 restructure -------------------------------',
  '# The six capability pages moved under /solutions/ and picked up hyphens.',
  '# Hyphens are not cosmetic: Google reads "data-integration" as two words and',
  '# "dataintegration" as one.',
  '',
];

let count = 0;
for (const page of MOVED) {
  for (const lang of LANGUAGES) {
    const from = `${prefixFor(lang)}/${page.legacySlug}`;
    const to = `${prefixFor(lang)}/${page.slug}/`;
    lines.push(`${from}      ${to}   301`);
    lines.push(`${from}/     ${to}   301`);
    count += 2;
  }
  lines.push('');
}

// /home duplicated / at 200 in every locale.
lines.push('# --- One home URL per locale --------------------------------------------');
lines.push('# Both cases: Netlify normalizes paths when SERVING a file but not when');
lines.push('# MATCHING a rule, so /Home needs its own line or it 404s.');
for (const lang of LANGUAGES) {
  for (const variant of ['home', 'Home']) {
    lines.push(`${prefixFor(lang)}/${variant}     ${prefixFor(lang)}/   301`);
    count += 1;
  }
}
lines.push('');

const out = path.resolve(__dirname, '..', 'public', '_redirects');
await writeFile(out, lines.join('\n') + '\n');
console.log(
  `Wrote ${out} — ${count} rules for ${MOVED.length} moved pages × ${LANGUAGES.length} locales ` +
  `(${PAGES.length - MOVED.length} pages kept their path).`,
);
